    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    email VARCHAR(255) NOT NULL,
    name VARCHAR(255) NOT NULL,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(255) NOT NULL,
    CONSTRAINT users_pkey PRIMARY KEY (id),
    CONSTRAINT uk6dotkott2kjsp8vw4d0m25fb7 UNIQUE (email)
);

CREATE TABLE urls (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    active BOOLEAN NOT NULL,
    click_count INTEGER NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    description VARCHAR(500),
    expiry_date TIMESTAMP(6),
    original_url VARCHAR(2048) NOT NULL,
    password_hash VARCHAR(255),
    password_protected BOOLEAN NOT NULL,
    short_code VARCHAR(30) NOT NULL,
    title VARCHAR(255),
    updated_at TIMESTAMP(6) NOT NULL,
    user_id BIGINT NOT NULL,
    CONSTRAINT urls_pkey PRIMARY KEY (id),
    CONSTRAINT uko6lree3tj9uru7b4vo07v6s1n UNIQUE (short_code),
    CONSTRAINT fk31nbxw9e1inas1lmdkwxqv10 FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE clicks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    browser VARCHAR(255),
    clicked_at TIMESTAMP(6),
    device VARCHAR(255),
    ip_address VARCHAR(255),
    operating_system VARCHAR(255),
    referrer VARCHAR(255),
    url_id BIGINT NOT NULL,
    CONSTRAINT clicks_pkey PRIMARY KEY (id),
    CONSTRAINT fkfxtlx8lr3kir9q9dxucqao2g6 FOREIGN KEY (url_id) REFERENCES urls (id)
);
